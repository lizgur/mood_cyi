/**
 * Writes src/lib/blogCatalog.generated.ts from src/content/blog/*.md.
 * The generated module is imported by the sitemap so post URLs are bundled
 * into the serverless function and do not depend on fs at request time.
 */
const fs = require("fs");
const path = require("path");
const matter = require("gray-matter");

const blogDir = path.join(__dirname, "../src/content/blog");
const outFile = path.join(__dirname, "../src/lib/blogCatalog.generated.ts");

function toIsoDate(value) {
  if (!value) return undefined;
  const date = value instanceof Date ? value : new Date(value);
  if (Number.isNaN(date.getTime())) return undefined;
  return date.toISOString().slice(0, 10);
}

function generateBlogCatalog() {
  if (!fs.existsSync(blogDir) || !fs.lstatSync(blogDir).isDirectory()) {
    throw new Error(`Blog content directory not found: ${blogDir}`);
  }

  const entries = fs
    .readdirSync(blogDir)
    .filter((file) => file.endsWith(".md") && !file.startsWith("_"))
    .map((filename) => {
      const raw = fs.readFileSync(path.join(blogDir, filename), "utf8");
      const { data } = matter(raw);
      const slug = data.url
        ? String(data.url).replace(/^\//, "")
        : filename.replace(/\.md$/, "");
      return {
        slug,
        date: toIsoDate(data.date),
        draft: Boolean(data.draft),
      };
    })
    .sort((a, b) => a.slug.localeCompare(b.slug));

  if (entries.length === 0) {
    throw new Error(`No blog posts found in ${blogDir}`);
  }

  const body = `// Generated by scripts/generate-blog-catalog.js — do not edit by hand.
export type BlogCatalogEntry = {
  slug: string;
  date?: string;
  draft?: boolean;
};

export const blogCatalog: BlogCatalogEntry[] = ${JSON.stringify(entries, null, 2)};
`;

  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, body);
  return entries;
}

if (require.main === module) {
  const entries = generateBlogCatalog();
  console.log(
    `Wrote ${path.relative(process.cwd(), outFile)} (${entries.length} post${
      entries.length === 1 ? "" : "s"
    })`,
  );
}

module.exports = generateBlogCatalog;
